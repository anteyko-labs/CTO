/** Документ с реквизитами точки и подписью руководителя — HTML для печати и предпросмотра. */
export function extraDocHtml(text: string, seller: Seller, sellerSignature: string | null, today = todayBishkek()): string {
  const [y, m, d] = today.split('-')
  return renderTemplate(
    text,
    {
      дата: `${d}.${m}.${y}`,
      город: seller.city,
      продавец: seller.name,
      инн_продавца: seller.inn,
      адрес_продавца: seller.address,
      телефон_продавца: seller.phone,
      руководитель: seller.director,
    },
    { подпись_продавца: signatureSlot(sellerSignature) },
  )
}

/** Печать в окне браузера: `copies` экземпляров, каждый с нового листа. */
export function printExtraDoc(doc: ExtraDoc, seller: Seller, sellerSignature: string | null, copies = 2): void {
  const one = `<div class="copy"><div class="doc">${extraDocHtml(doc.text, seller, sellerSignature)}</div></div>`
  printHtml(doc.title, Array.from({ length: copies }, () => one).join(''))
}
