// Когда новую версию интерфейса можно применить самой, без кнопки (ADR-058, ADR-059).
// Отдельно от updates.ts, чтобы правило проверялось тестом без Service Worker.

export interface UpdateMoment {
  /** Путь страницы: касса — «/». */
  path: string
  cartEmpty: boolean
  /** Открыто окно (модальное): в нём может быть недописанная форма. */
  modalOpen: boolean
  visible: boolean
}

/**
 * Сама — только на кассе с пустым чеком и без открытого окна: моноблок открыт всегда, и иначе
 * версия не обновилась бы никогда. На других экранах (приход, ревизия, возврат, закрытие смены,
 * карточка товара) форма живёт только в памяти — там только плашка «Обновить».
 */
export function canAutoApply(m: UpdateMoment): boolean {
  return m.path === '/' && m.cartEmpty && !m.modalOpen && m.visible
}
