import { describe, expect, it } from 'vitest'
import { mapUmagRows, preselected, serviceCandidates } from './umag'

const sheet = [
  ['Название товара', 'Штрихкод', 'Артикул', 'Доп. код', 'Закупочная цена', 'Прод. цена', 'Ед. изм.', 'Поставщик', 'Категория'],
  ['Масло ZIC X7 5W-30 4L', '8801111111111', 'ZIC-X7', '', '1800', '2600', 'Литр', 'Ойл-Трейд', 'Моторные масла'],
  ['Свеча NGK BKR6E', '4900000000011', 'BKR6E', '', '150', '300', 'шт', 'Автоснаб', 'Автохимия'],
  ['Замена масла', '', '', '', '', '200', 'шт', '', 'Незаданные'],
  ['Мойка двигателя', '', '', '', '0', '500', 'шт.', '', 'Услуги'],
  ['Замена антифриза', '', '', '', '', '400', '', '', ''],
  ['Свинец', '', '', '', '', '80', 'кг', '', 'Незаданные'],
  ['мойка двигателя', '', '', '', '', '550', 'шт', '', 'Незаданные'],
  ['', '', '', '', '', '100', 'шт', '', 'Незаданные'],
]

describe('выгрузка старой программы', () => {
  it('столбцы по заголовкам, суммы в тыйынах', () => {
    const rows = mapUmagRows(sheet)
    expect(rows[0]).toMatchObject({ name: 'Масло ZIC X7 5W-30 4L', cost_tyiyn: 180_000, price_tyiyn: 260_000, unit: 'Литр', category: 'Моторные масла' })
    expect(() => mapUmagRows([['Что-то']])).toThrow('Название товара')
  })

  it('услуги: похожие отмечены, существующие и повторы — не загружаются', () => {
    const list = serviceCandidates(mapUmagRows(sheet), ['ЗАМЕНА МАСЛА'])
    expect(list.map((c) => [c.name, c.likely, c.exists])).toEqual([
      ['Мойка двигателя', true, false],
      ['Замена антифриза', true, false],
      ['Масло ZIC X7 5W-30 4L', false, false],
      ['Свеча NGK BKR6E', false, false],
      ['Свинец', false, false],
      ['Замена масла', true, true],
    ])
    expect([...preselected(list)]).toEqual(['Мойка двигателя', 'Замена антифриза'])
    expect(list.find((c) => c.name === 'Мойка двигателя')?.price_tyiyn).toBe(50_000)
  })
})
