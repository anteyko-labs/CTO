-- «Прибыль и убытки» (задача 003 Н12, SPEC-08, ADR-157, ADR-158).

-- 1. «Кому» у расхода: кому отдали деньги («Иман», «Электросети»). Пусто — не указано (прежние
--    расходы). Пишется при проведении и не правится: исправить — «Исправить» (сторно + новый,
--    I4); сторно повторяет «Кому» исходного. Колонка с постоянным значением по умолчанию не
--    переписывает строки: запрет правки расходов (триггер `expenses_immutable`) не срабатывает.
alter table expenses add column payee text not null default '';

-- Подсказки «Кому» в форме расхода — прежние значения филиала, последние сначала.
create index expenses_payee_idx on expenses (branch_id, created_at desc) where payee <> '';

-- 2. «Выдано работникам» за период в отчёте о прибыли — выплаты филиала по дате выплаты
--    (`payouts.pay_date`, 0083, ADR-154): как «Выдано» в итогах (`payroll::staff_pay`).
create index payouts_branch_pay_date_idx on payouts (branch_id, pay_date);
