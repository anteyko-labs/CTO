-- Задача 003 (хвост ADR-139): при смене единицы товара выключенное правило подарка с порогом
-- (или количеством подарка), который не переходит в новую единицу целым числом, не блокирует
-- пересчёт — значение округляется, правило помечается «поправьте порог» и остаётся выключенным,
-- пока владелец не сохранит его заново.
alter table gift_rules add column needs_fix boolean not null default false;
